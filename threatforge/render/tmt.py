"""
Microsoft Threat Modeling Tool (.tm7) export.

The import side turns an archive of TMT models into a live baseline. This is the
other half: it lets a model ThreatForge generated from infrastructure-as-code be
opened in TMT, so analysts who work in that tool can review, annotate, and
extend a diagram nobody had to draw.

Together the two make the integration bidirectional:

    TMT model ──import──> ThreatForge ──scan + analyse──> .tm7 ──> TMT

Format notes
------------
`.tm7` is a .NET DataContract serialisation, which is stricter than ordinary
XML: element order, namespace prefixes, and `i:type` discriminators all matter
to the deserialiser. This module emits text rather than using ElementTree,
because ElementTree rewrites namespace prefixes and DataContract will not accept
the result.

Shape classes are fixed by the schema:

    GE.EI   external interactor -> StencilRectangle
    GE.P    process             -> StencilEllipse
    GE.DS   data store          -> StencilParallelLines
    GE.TB.B trust boundary      -> BorderBoundary
    GE.DF   data flow           -> Connector

Verification status
-------------------
Output is schema-conformant and round-trips through our own importer with no
loss of elements, flows, or boundaries. It has **not** been opened in Microsoft
TMT itself, which needs Windows and a TMT installation. Treat TMT compatibility
as expected-but-unverified until you have opened one; see `docs/INTEROP.md`.
"""

from __future__ import annotations

import uuid
from datetime import date
from typing import Any, Dict, List, Optional, Tuple
from xml.sax.saxutils import escape

from ..model import Element, Severity, ThreatModel

SCHEMA_VERSION = "4.3"

NS_MODEL = "http://schemas.datacontract.org/2004/07/ThreatModeling.Model"
NS_ABS = "http://schemas.datacontract.org/2004/07/ThreatModeling.Model.Abstracts"
NS_ARR = "http://schemas.microsoft.com/2003/10/Serialization/Arrays"
NS_KB = "http://schemas.datacontract.org/2004/07/ThreatModeling.KnowledgeBase"
NS_SER = "http://schemas.microsoft.com/2003/10/Serialization/"
NS_XSI = "http://www.w3.org/2001/XMLSchema-instance"
NS_XSD = "http://www.w3.org/2001/XMLSchema"

# A fixed namespace so the same asset always exports as the same GUID. Without
# this, every export produces a new set of ids and TMT sees a brand-new model
# each time, losing any annotation the analyst added.
GUID_NAMESPACE = uuid.UUID("6f1c6b6e-6f2a-5a1e-9c3d-7f4b2a8e5d10")

ELEMENT_STENCIL = {
    Element.EXTERNAL_ENTITY: ("GE.EI", "StencilRectangle", "SE.EI.Ext"),
    Element.PROCESS: ("GE.P", "StencilEllipse", "SE.P.TWS"),
    Element.DATA_STORE: ("GE.DS", "StencilParallelLines", "SE.DS.SQL"),
}

# Protocol -> the TMT flow stencil that carries the same meaning.
PROTOCOL_STENCIL = [
    ("https", "SE.DF.HTTPS"), ("tls", "SE.DF.HTTPS"), ("mtls", "SE.DF.HTTPS"),
    ("http", "SE.DF.HTTP"), ("sql", "SE.DF.SQL"), ("postgres", "SE.DF.SQL"),
    ("mysql", "SE.DF.SQL"), ("grpc", "SE.DF.RPC"), ("rpc", "SE.DF.RPC"),
]

STRIDE_CATEGORY = {
    "S": "Spoofing", "T": "Tampering", "R": "Repudiation",
    "I": "Information Disclosure", "D": "Denial of Service",
    "E": "Elevation of Privilege",
}

# `Critical` is a real member -- a genuine export uses it -- so criticals are
# not flattened into High.
PRIORITY = {
    Severity.CRITICAL: "Critical", Severity.HIGH: "High",
    Severity.MEDIUM: "Medium", Severity.LOW: "Low", Severity.INFO: "Low",
}

# ThreatState is an enum on the .NET side, and DataContractSerializer throws on
# a member it does not recognise -- which surfaces to the user as "the file
# could not be deserialized", with nothing to say which element was at fault.
# Only values observed in a real export are used. Ours are produced by an
# engine, so `AutoGenerated` is the honest mapping; the states a human sets in
# TMT are theirs to set.
THREAT_STATE = "AutoGenerated"

COL_W, ROW_H = 260, 140
ORIGIN_X, ORIGIN_Y = 60, 80
SHAPE_W, SHAPE_H = 120, 90
MAX_ROWS = 10


def guid_for(asset_id: str) -> str:
    return str(uuid.uuid5(GUID_NAMESPACE, asset_id))


def _esc(text: Any) -> str:
    return escape(str(text if text is not None else ""), {'"': "&quot;", "'": "&#39;"})


def _stencil_for_protocol(protocol: Optional[str]) -> str:
    p = (protocol or "").lower()
    for needle, stencil in PROTOCOL_STENCIL:
        if needle in p:
            return stencil
    return "SE.DF.Binary"


