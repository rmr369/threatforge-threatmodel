def render(model: ThreatModel, *, include_findings: bool = True,
           max_findings: int = 200, document: Optional[Dict[str, Any]] = None) -> str:
    assets = [a for a in model.assets.values()
              if a.element in ELEMENT_STENCIL and a.kind != "Container"]
    flagged = {f.component for f in model.active_findings}
    assets += [a for a in model.assets.values()
               if a.kind == "Container" and a.id in flagged
               and a.element in ELEMENT_STENCIL]

    positions = _layout(assets)
    keep = {a.id for a in assets}
    surface_guid = guid_for("__surface__")

    out: List[str] = []
    w = out.append
    w('<?xml version="1.0" encoding="utf-8"?>')
    w(f'<ThreatModel xmlns="{NS_MODEL}" xmlns:i="{NS_XSI}">')
    w('  <DrawingSurfaceList>')
    w(f'    <DrawingSurfaceModel z:Id="i1" xmlns:z="{NS_SER}">')
    w(f'      <GenericTypeId xmlns="{NS_ABS}">DRAWINGSURFACE</GenericTypeId>')
    w(f'      <Guid xmlns="{NS_ABS}">{surface_guid}</Guid>')
    w(f'      <Properties xmlns="{NS_ABS}" xmlns:a="{NS_ARR}">')
    w(f'        <a:anyType i:type="b:HeaderDisplayAttribute" xmlns:b="{NS_KB}">')
    w('          <b:DisplayName>Diagram</b:DisplayName>')
    w('          <b:Name/>')
    w('          <b:Value i:nil="true"/>')
    w('        </a:anyType>')
    w(f'        <a:anyType i:type="b:StringDisplayAttribute" xmlns:b="{NS_KB}">')
    w('          <b:DisplayName>Name</b:DisplayName>')
    w('          <b:Name/>')
    w(f'          <b:Value i:type="c:string" xmlns:c="{NS_XSD}">'
      f'{_esc(model.project)} — generated DFD</b:Value>')
    w('        </a:anyType>')
    w('      </Properties>')
    w(f'      <TypeId xmlns="{NS_ABS}">DRAWINGSURFACE</TypeId>')

    # -- shapes -----------------------------------------------------------
    w(f'      <Borders xmlns:a="{NS_ARR}">')
    zid = _ZCounter()
    for a in assets:
        generic, klass, type_id = ELEMENT_STENCIL[a.element]
        x, y = positions[a.id]
        w(_shape(guid_for(a.id), generic, klass, type_id, a.name,
                 x, y, SHAPE_W, SHAPE_H, _describe(a), zid.next()))
    for b, rect in _boundary_rects(model, assets, positions):
        w(_shape(guid_for(b.id), "GE.TB.B", "BorderBoundary", "SE.TB.B", b.name,
                 rect[0], rect[1], rect[2], rect[3], b.description, zid.next()))
    w('      </Borders>')
    w(f'      <Header>{_esc(model.project)} — generated DFD</Header>')

    # -- flows ------------------------------------------------------------
    w(f'      <Lines xmlns:a="{NS_ARR}">')
    flow_endpoints: Dict[str, Tuple[str, str]] = {}
    n = 0
    for f in model.flows:
        if f.source not in keep or f.target not in keep:
            continue
        if f.kind in ("protects", "runs"):
            continue
        n += 1
        sx, sy = positions[f.source]
        tx, ty = positions[f.target]
        label = f.details.get("name") or f.kind.replace("-", " ")
        flow_endpoints[f.id] = (guid_for(f.source), guid_for(f.target))
        w(_connector(guid_for(f.id), _stencil_for_protocol(f.protocol), label,
                     guid_for(f.source), guid_for(f.target),
                     sx + SHAPE_W, sy + SHAPE_H // 2, tx, ty + SHAPE_H // 2,
                     zid.next()))
    w('      </Lines>')
    w('      <Zoom>1</Zoom>')
    w('    </DrawingSurfaceModel>')
    w('  </DrawingSurfaceList>')

    # -- metadata ---------------------------------------------------------
    counts = model.counts()
    description = (
        f"Generated by ThreatForge from infrastructure-as-code on "
        f"{date.today().isoformat()}.\n"
        f"{len(model.assets)} assets, {len(model.flows)} data flows, "
        f"{len(model.active_findings)} evidence-backed findings "
        f"({counts['critical']} critical, {counts['high']} high).\n"
        f"Every threat below cites the file and line that produced it. "
        f"Elements you add here can be fed back in via the .tm7 importer.")
    # The document fields map onto MetaInformation, which is where TMT keeps
    # the same information -- so a title and an owner written here survive the
    # trip into TMT and back rather than living only in our own store.
    doc = (document or {}).get("fields", {}) if document else {}
    def _f(key: str, fallback: str = "") -> str:
        return _esc(str(doc.get(key) or fallback))
    w('  <MetaInformation>')
    w(f'    <Assumptions>{_f("assumptions")}</Assumptions>')
    w(f'    <Contributors>{_f("stakeholders", "ThreatForge")}</Contributors>')
    w(f'    <ExternalDependencies>{_f("dependencies")}</ExternalDependencies>')
    w(f'    <HighLevelSystemDescription>{_f("scope") or _esc(description)}'
      '</HighLevelSystemDescription>')
    w(f'    <Owner>{_f("owner")}</Owner>')
    w(f'    <Reviewer>{_f("reviewer")}</Reviewer>')
    w(f'    <ThreatModelName>{_f("title", model.project)}</ThreatModelName>')
    w('  </MetaInformation>')
    w('  <Notes/>')

    # -- threats ----------------------------------------------------------
    w(f'  <ThreatInstances xmlns:a="{NS_ARR}">')
    if include_findings:
        i = 0
        for f in model.active_findings[:max_findings]:
            if f.component not in keep and f.component not in flow_endpoints:
                continue
            i += 1
            w(_threat(f, i, surface_guid, flow_endpoints))
    w('  </ThreatInstances>')

    w('  <ThreatGenerationEnabled>false</ThreatGenerationEnabled>')
    w('  <Validations/>')
    w(f'  <Version>{SCHEMA_VERSION}</Version>')
    # TMT expects these two after Version. The KnowledgeBase in a real export is
    # the whole SDL template -- several hundred kilobytes of stencil and threat
    # definitions we neither own nor need to reproduce. Emitting the element
    # empty lets the file deserialise and TMT supplies its own template; copying
    # Microsoft's content would be redistributing their template, which is a
    # different thing from writing their file format.
    # In a genuine export the object-reference ids run i1 for the surface, then
    # one per shape and connector, and the KnowledgeBase takes the next. Emitted
    # empty: the real one is Microsoft's template, and TMT supplies its own.
    w(f'  <KnowledgeBase z:Id="{zid.next()}" xmlns:z="{NS_SER}"/>')
    # PromptedKb carries no namespace at all in a genuine export -- it is not
    # in Model, and putting it there is exactly the kind of near-miss that makes
    # DataContractSerializer refuse the whole document.
    w('  <Profile>')
    w('    <PromptedKb xmlns=""/>')
    w('  </Profile>')
    w('</ThreatModel>')
    return "\n".join(out) + "\n"


