class _ZCounter:
    """Object-reference ids. `i1` is the drawing surface, so shapes start at i2."""

    def __init__(self, start: int = 2) -> None:
        self._n = start

    def next(self) -> str:
        v = f"i{self._n}"
        self._n += 1
        return v


def _shape(guid: str, generic: str, klass: str, type_id: str, name: str,
           left: int, top: int, width: int, height: int,
           description: str = "", zid: str = "i2") -> str:
    props = [_string_prop("Name", name)]
    if description:
        props.append(_string_prop("Description", description))
    props.append(_bool_prop("Out Of Scope", False))
    body = "\n".join(props)
    return (
        f'        <a:KeyValueOfguidanyType>\n'
        f'          <a:Key>{guid}</a:Key>\n'
        f'          <a:Value z:Id="{zid}" i:type="{klass}">\n'
        f'            <GenericTypeId xmlns="{NS_ABS}">{generic}</GenericTypeId>\n'
        f'            <Guid xmlns="{NS_ABS}">{guid}</Guid>\n'
        f'            <Properties xmlns="{NS_ABS}" xmlns:a="{NS_ARR}">\n'
        f'{body}\n'
        f'            </Properties>\n'
        f'            <TypeId xmlns="{NS_ABS}">{type_id}</TypeId>\n'
        f'            <Height xmlns="{NS_ABS}">{height}</Height>\n'
        f'            <Left xmlns="{NS_ABS}">{left}</Left>\n'
        f'            <StrokeDashArray xmlns="{NS_ABS}" i:nil="true"/>\n'
        f'            <StrokeThickness xmlns="{NS_ABS}">1</StrokeThickness>\n'
        f'            <Top xmlns="{NS_ABS}">{top}</Top>\n'
        f'            <Width xmlns="{NS_ABS}">{width}</Width>\n'
        f'          </a:Value>\n'
        f'        </a:KeyValueOfguidanyType>'
    )


def _connector(guid: str, type_id: str, name: str, source: str, target: str,
               sx: int, sy: int, tx: int, ty: int, zid: str = "i2") -> str:
    return (
        f'        <a:KeyValueOfguidanyType>\n'
        f'          <a:Key>{guid}</a:Key>\n'
        f'          <a:Value z:Id="{zid}" i:type="Connector">\n'
        f'            <GenericTypeId xmlns="{NS_ABS}">GE.DF</GenericTypeId>\n'
        f'            <Guid xmlns="{NS_ABS}">{guid}</Guid>\n'
        f'            <Properties xmlns="{NS_ABS}" xmlns:a="{NS_ARR}">\n'
        f'{_string_prop("Name", name)}\n'
        f'            </Properties>\n'
        f'            <TypeId xmlns="{NS_ABS}">{type_id}</TypeId>\n'
        f'            <HandleX xmlns="{NS_ABS}">{(sx + tx) // 2}</HandleX>\n'
        f'            <HandleY xmlns="{NS_ABS}">{(sy + ty) // 2}</HandleY>\n'
        f'            <PortSource xmlns="{NS_ABS}">East</PortSource>\n'
        f'            <PortTarget xmlns="{NS_ABS}">West</PortTarget>\n'
        f'            <SourceGuid xmlns="{NS_ABS}">{source}</SourceGuid>\n'
        f'            <SourceX xmlns="{NS_ABS}">{sx}</SourceX>\n'
        f'            <SourceY xmlns="{NS_ABS}">{sy}</SourceY>\n'
        f'            <TargetGuid xmlns="{NS_ABS}">{target}</TargetGuid>\n'
        f'            <TargetX xmlns="{NS_ABS}">{tx}</TargetX>\n'
        f'            <TargetY xmlns="{NS_ABS}">{ty}</TargetY>\n'
        f'          </a:Value>\n'
        f'        </a:KeyValueOfguidanyType>'
    )


def _header_prop(name: str) -> str:
    """A section heading in TMT's property grid. Value is nil, but present."""
    return (
        f'              <a:anyType i:type="b:HeaderDisplayAttribute" xmlns:b="{NS_KB}">\n'
        f'                <b:DisplayName>{_esc(name)}</b:DisplayName>\n'
        f'                <b:Name/>\n'
        f'                <b:Value i:nil="true"/>\n'
        f'              </a:anyType>'
    )


def _string_prop(name: str, value: Any, key: str = "") -> str:
    return (
        f'              <a:anyType i:type="b:StringDisplayAttribute" xmlns:b="{NS_KB}">\n'
        f'                <b:DisplayName>{_esc(name)}</b:DisplayName>\n'
        f'                {"<b:Name>" + _esc(key) + "</b:Name>" if key else "<b:Name/>"}\n'
        f'                <b:Value i:type="c:string" xmlns:c="{NS_XSD}">'
        f'{_esc(value)}</b:Value>\n'
        f'              </a:anyType>'
    )


def _bool_prop(name: str, value: bool, key: str = "") -> str:
    return (
        f'              <a:anyType i:type="b:BooleanDisplayAttribute" xmlns:b="{NS_KB}">\n'
        f'                <b:DisplayName>{_esc(name)}</b:DisplayName>\n'
        f'                {"<b:Name>" + _esc(key) + "</b:Name>" if key else "<b:Name/>"}\n'
        f'                <b:Value i:type="c:boolean" xmlns:c="{NS_XSD}">'
        f'{"true" if value else "false"}</b:Value>\n'
        f'              </a:anyType>'
    )


def _threat(finding, index: int, surface_guid: str,
            flow_endpoints: Dict[str, Tuple[str, str]]) -> str:
    """One ThreatInstance.

    DataContract serialises members alphabetically and the deserialiser is
    unforgiving about both order and namespace: every field below sits in the
    KnowledgeBase namespace (`b:`) while the property map uses Arrays (`a:`).
    Omitting a member, or swapping the two prefixes, makes TMT reject the file.
    """
    src = finding.primary_source
    where = ""
    if src and src.file:
        where = f"\n\nEvidence: {src.file}" + (f":{src.line}" if src.line else "")
    if finding.evidence:
        where += f"\n{finding.evidence[0].description}"
    r = finding.risk
    exposure = ("unreachable from an external entity" if r.exposure_hops is None
                else f"{r.exposure_hops} hop(s) from the internet")
    rationale = (f"\n\nRisk {finding.risk_score}/25 "
                 f"(likelihood {r.likelihood} x impact {r.impact}). "
                 f"Exposure: {exposure}. Blast radius {r.blast_radius}.")
    remediation = (f"\n\nRemediation: {finding.remediation.summary}"
                   if finding.remediation else "")
    description = (" ".join((finding.description or "").split())
                   + where + rationale + remediation)

    category = (STRIDE_CATEGORY.get(finding.stride[0], "Tampering")
                if finding.stride else "Tampering")
    priority = PRIORITY.get(finding.risk_level, "Medium")

    # A threat on a flow is an "interaction" in TMT: source shape, connector,
    # target shape. A threat on an element has no connector.
    if finding.component in flow_endpoints:
        a_guid, b_guid = flow_endpoints[finding.component]
        flow_guid = guid_for(finding.component)
        flow_el = f'        <b:FlowGuid>{flow_guid}</b:FlowGuid>\n'
        interaction = f"{a_guid}:{flow_guid}:{b_guid}"
        source_guid, target_guid = a_guid, b_guid
    else:
        source_guid = target_guid = guid_for(finding.component)
        flow_el = '        <b:FlowGuid i:nil="true"/>\n'
        interaction = source_guid

    props = "".join(
        f'          <a:KeyValueOfstringstring>\n'
        f'            <a:Key>{k}</a:Key>\n'
        f'            <a:Value>{_esc(v)}</a:Value>\n'
        f'          </a:KeyValueOfstringstring>\n'
        for k, v in (("Title", finding.title),
                     ("UserThreatCategory", category),
                     ("UserThreatDescription", description),
                     ("Priority", priority)))

    return (
        f'    <a:KeyValueOfstringThreatpc_P0_PhOB>\n'
        f'      <a:Key>{_esc(finding.id)}</a:Key>\n'
        f'      <a:Value xmlns:b="{NS_KB}">\n'
        f'        <b:ChangedBy i:nil="true"/>\n'
        f'        <b:DrawingSurfaceGuid>{surface_guid}</b:DrawingSurfaceGuid>\n'
        f'{flow_el}'
        f'        <b:Id>{index}</b:Id>\n'
        f'        <b:InteractionKey>{interaction}</b:InteractionKey>\n'
        f'        <b:InteractionString i:nil="true"/>\n'
        f'        <b:ModifiedAt>0001-01-01T00:00:00</b:ModifiedAt>\n'
        f'        <b:Priority>{priority}</b:Priority>\n'
        f'        <b:Properties>\n'
        f'{props}'
        f'        </b:Properties>\n'
        f'        <b:SourceGuid>{source_guid}</b:SourceGuid>\n'
        f'        <b:State>{THREAT_STATE}</b:State>\n'
        f'        <b:StateInformation>{_esc(finding.rule_id)}</b:StateInformation>\n'
        f'        <b:TargetGuid>{target_guid}</b:TargetGuid>\n'
        f'        <b:Title>{_esc(finding.title)}</b:Title>\n'
        f'        <b:TypeId>{_esc(finding.rule_id)}</b:TypeId>\n'
        f'        <b:Upgraded>false</b:Upgraded>\n'
        f'        <b:UserThreatCategory>{_esc(category)}</b:UserThreatCategory>\n'
        f'        <b:UserThreatDescription>{_esc(description)}'
        f'</b:UserThreatDescription>\n'
        f'        <b:UserThreatShortDescription>{_esc(finding.title)}'
        f'</b:UserThreatShortDescription>\n'
        f'        <b:Wide>false</b:Wide>\n'
        f'      </a:Value>\n'
        f'    </a:KeyValueOfstringThreatpc_P0_PhOB>'
    )


def _layout(assets: List) -> Dict[str, Tuple[int, int]]:
    """Columns by distance from the internet -- the order an attacker walks."""
    columns: Dict[int, List] = {}
    for a in assets:
        hops = a.facts.get("exposure_hops")
        col = 9 if hops is None else min(int(hops), 8)
        columns.setdefault(col, []).append(a)
    out: Dict[str, Tuple[int, int]] = {}
    for col in sorted(columns):
        for i, a in enumerate(columns[col]):
            out[a.id] = (ORIGIN_X + col * COL_W,
                         ORIGIN_Y + (i % MAX_ROWS) * ROW_H + (i // MAX_ROWS) * 30)
    return out


def _boundary_rects(model: ThreatModel, assets: List,
                    positions: Dict[str, Tuple[int, int]]):
    """TMT boundaries are rectangles, so draw one around each set of members."""
    keep = {a.id for a in assets}
    for b in sorted(model.boundaries.values(), key=lambda x: -x.trust_level):
        members = [m for m in b.members if m in keep and m in positions]
        if len(members) < 2:
            continue        # a box around one shape adds nothing
        xs = [positions[m][0] for m in members]
        ys = [positions[m][1] for m in members]
        pad = 24
        left, top = min(xs) - pad, min(ys) - pad
        width = (max(xs) + SHAPE_W + pad) - left
        height = (max(ys) + SHAPE_H + pad) - top
        yield b, (left, top, width, height)


def _describe(asset) -> str:
    bits = [asset.display]
    if asset.data_classes:
        bits.append("handles " + ", ".join(sorted(dc.value for dc in asset.data_classes)))
    hops = asset.facts.get("exposure_hops")
    if hops is not None:
        bits.append(f"{hops} hop(s) from the internet")
    return " | ".join(bits)
