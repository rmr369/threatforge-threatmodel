def _describe(asset) -> str:
    bits = [asset.display]
    if asset.data_classes:
        bits.append("handles " + ", ".join(sorted(dc.value for dc in asset.data_classes)))
    hops = asset.facts.get("exposure_hops")
    if hops == 0:
        bits.append("untrusted entry point")
    elif hops is not None:
        bits.append(f"{hops} hop(s) from the internet")
    else:
        bits.append("no path from an external entity")
    blast = asset.facts.get("blast_radius")
    if blast:
        bits.append(f"blast radius {blast}")
    return " · ".join(bits)


def _technologies(asset) -> List[str]:
    out: List[str] = []
    for t in asset.tags:
        if t.startswith("image:"):
            image = t.split(":", 1)[1]
            out.append(image.split("/")[-1].split("@")[0])
    if asset.provider and asset.provider not in ("manual", "external"):
        out.append(asset.provider)
    if asset.kind and asset.kind not in ("Container",):
        out.append(asset.kind)
    seen, uniq = set(), []
    for t in out:
        if t and t not in seen:
            seen.add(t)
            uniq.append(t)
    return uniq[:5]


def _plain(value: Any) -> Any:
    """YAML-safe scalars only -- observed values can be sets or enums."""
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    if isinstance(value, (list, tuple, set)):
        return [_plain(v) for v in value]
    if isinstance(value, dict):
        return {str(k): _plain(v) for k, v in value.items()}
    return str(value)
